// An object's `Cache-Control`: fixed on upload (preset, validated string, per-prefix rule, or the
// default) and the worker serves it as-is; the edge TTL comes from its `s-maxage`/`max-age`. Pure: shared by the SDK
// and the worker.
import { normalizeAssetPrefix } from "./assets";

export const CacheControlPreset = {
	/** Versioned files (hash in the name or `?v=`): never change under the same URL. */
	IMMUTABLE: "immutable",
	/** Files that keep their name: a day, and served stale while revalidating. */
	REVALIDATE: "revalidate",
	/** Always revalidate (entry HTML, manifests). */
	NO_CACHE: "no-cache",
} as const;

export type CacheControlPreset = (typeof CacheControlPreset)[keyof typeof CacheControlPreset];

export const CACHE_CONTROL_PRESETS: Record<CacheControlPreset, string> = {
	immutable: "public, max-age=31536000, immutable",
	revalidate: "public, max-age=86400, stale-while-revalidate=86400",
	"no-cache": "public, no-cache",
};

/** Default for an asset (client path) with no rule: short, so a replacement shows in ~1 min even without a purge. */
export const DEFAULT_ASSET_CACHE_CONTROL = "public, max-age=60, stale-while-revalidate=86400";
/** Ids generated by the worker: the URL is never reused. */
export const GENERATED_PUBLIC_CACHE_CONTROL = CACHE_CONTROL_PRESETS.immutable;
export const GENERATED_PRIVATE_CACHE_CONTROL = "private, max-age=31536000, immutable";

export const MAX_CACHE_CONTROL_LENGTH = 200;
export const MAX_CACHE_RULES = 50;
const MAX_AGE_SECONDS = 31536000;

const FLAG_DIRECTIVES = new Set([
	"public",
	"private",
	"no-cache",
	"no-store",
	"immutable",
	"must-revalidate",
	"proxy-revalidate",
	"no-transform",
]);
const SECONDS_DIRECTIVES = new Set(["max-age", "s-maxage", "stale-while-revalidate", "stale-if-error"]);

function parseDirective(raw: string): [string, number | null] | null {
	const [name = "", value, ...extra] = raw.trim().toLowerCase().split("=");
	if (extra.length > 0) return null;
	if (FLAG_DIRECTIVES.has(name)) return value === undefined ? [name, null] : null;
	if (!SECONDS_DIRECTIVES.has(name) || value === undefined || !/^\d{1,9}$/.test(value)) return null;
	const seconds = Number(value);
	return seconds <= MAX_AGE_SECONDS ? [name, seconds] : null;
}

/** Directives of a valid `Cache-Control` (name → seconds or null). `null` if something is invalid. */
function parseCacheControl(value: string): Map<string, number | null> | null {
	if (value.length === 0 || value.length > MAX_CACHE_CONTROL_LENGTH) return null;
	const directives = new Map<string, number | null>();
	for (const raw of value.split(",")) {
		const directive = parseDirective(raw);
		if (!directive || directives.has(directive[0])) return null;
		directives.set(directive[0], directive[1]);
	}
	if (directives.has("public") && directives.has("private")) return null;
	return directives;
}

function formatDirectives(directives: Map<string, number | null>): string {
	return [...directives].map(([name, seconds]) => (seconds === null ? name : `${name}=${seconds}`)).join(", ");
}

/**
 * Preset (`immutable` | `revalidate` | `no-cache`) or raw string → normalized `Cache-Control`. `null` if it's not
 * valid: directives outside the whitelist, non-integer seconds or > 1 year, repeated, `public` + `private`, or more
 * than {@link MAX_CACHE_CONTROL_LENGTH} characters.
 */
export function resolveCacheControl(input: unknown): string | null {
	if (typeof input !== "string") return null;
	const preset = CACHE_CONTROL_PRESETS[input.trim() as CacheControlPreset];
	if (preset) return preset;
	const directives = parseCacheControl(input);
	return directives ? formatDirectives(directives) : null;
}

/**
 * Seconds the edge copy may live: `s-maxage`, otherwise `max-age`, capped at `maxSeconds`. 0 = don't cache
 * at the edge (`no-store`, `no-cache`, `private`, or no age given).
 */
export function edgeTtlSeconds(cacheControl: string | null | undefined, maxSeconds: number): number {
	const directives = cacheControl ? parseCacheControl(cacheControl) : null;
	if (!directives) return 0;
	if (directives.has("no-store") || directives.has("no-cache") || directives.has("private")) return 0;
	const seconds = directives.get("s-maxage") ?? directives.get("max-age") ?? 0;
	return Math.min(seconds, maxSeconds);
}

/** The same `Cache-Control` for a private object: only the browser stores it (never a shared cache). */
export function toPrivateCacheControl(cacheControl: string): string {
	const directives = parseCacheControl(cacheControl);
	if (!directives) return GENERATED_PRIVATE_CACHE_CONTROL;
	for (const shared of ["public", "private", "s-maxage", "proxy-revalidate"]) directives.delete(shared);
	return formatDirectives(new Map([["private", null], ...directives]));
}

/** Config per-prefix rule. `prefix` is relative to the `asset/` namespace (`site/static/`); `""` = everything. */
export interface CacheRule {
	prefix: string;
	cacheControl: string;
}

/** Normalizes and validates the rules (unique prefixes, valid `Cache-Control`). `null` if any isn't. */
export function normalizeCacheRules(raw: unknown): CacheRule[] | null {
	if (!Array.isArray(raw) || raw.length > MAX_CACHE_RULES) return null;
	const rules: CacheRule[] = [];
	for (const candidate of raw as Array<Partial<CacheRule>>) {
		const rawPrefix = typeof candidate?.prefix === "string" ? candidate.prefix.trim() : null;
		const prefix = rawPrefix === "" ? "" : normalizeAssetPrefix(rawPrefix);
		const cacheControl = resolveCacheControl(candidate?.cacheControl);
		if (prefix === null || !cacheControl || rules.some((rule) => rule.prefix === prefix)) return null;
		rules.push({ prefix, cacheControl });
	}
	return rules;
}

/** Rule for an asset's path (`site/app.js`): the longest prefix wins. `null` if none applies. */
export function matchCacheRule(rules: readonly CacheRule[] | undefined, assetPath: string): CacheRule | null {
	let best: CacheRule | null = null;
	for (const rule of rules ?? []) {
		if (!assetPath.startsWith(rule.prefix)) continue;
		if (!best || rule.prefix.length > best.prefix.length) best = rule;
	}
	return best;
}
