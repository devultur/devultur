// Composable security building blocks (L3 binding + L4 encryption). Named flags,
// secure-by-default. Replace the `SecurityConfig { level, sessionFingerprint, aes128Hls }` (dead
// config): `level` 1-4 is deprecated in favor of these explicit flags.

export interface SecurityPolicy {
	/** L3 base: ties the viewer token to `userId` + session fingerprint (userAgent + nonce). Default ON. */
	sessionBinding?: boolean;
	/** L3+: adds the IP to the fingerprint (stricter; breaks with mobile data/VPN). Opt-in. Default OFF. */
	ipBinding?: boolean;
	/** L4: encrypts the private asset (HLS AES-128 for video; AES-CTR at-rest for image/file). Opt-in. Default OFF. */
	encrypt?: boolean;
}

/** Default effective policy: session binding on (closes off a stolen token), IP + encrypt off. */
export const DEFAULT_SECURITY: Required<SecurityPolicy> = {
	sessionBinding: true,
	ipBinding: false,
	encrypt: false,
};

/**
 * Resolves the effective policy: resource override → `configured` (the config's default) →
 * secure-default. Each flag is resolved independently (same spirit as `resolveVisibility`).
 */
export function resolveSecurity(resource?: SecurityPolicy, configured?: SecurityPolicy): Required<SecurityPolicy> {
	return {
		sessionBinding: resource?.sessionBinding ?? configured?.sessionBinding ?? DEFAULT_SECURITY.sessionBinding,
		ipBinding: resource?.ipBinding ?? configured?.ipBinding ?? DEFAULT_SECURITY.ipBinding,
		encrypt: resource?.encrypt ?? configured?.encrypt ?? DEFAULT_SECURITY.encrypt,
	};
}

/** Header carrying the client's session secret on every delivery request (session binding). */
export const SESSION_HEADER = "X-Devultur-Session";

/**
 * Session fingerprint (SHA-256 hex). Without `ip` → `fp` (session binding); with `ip` → `fpip` (session + IP).
 * The `sessionSecret` (generated by the client, kept in memory, and sent in `${SESSION_HEADER}` on delivery)
 * is what ties the token to the browser session — it works even if the token is issued
 * server-side and is a real binding: a leaked URL with `?token=` is useless without the header. The `nonce`
 * makes it unique per token. Pure: issuance (`/v1/token`) and the delivery gate use it IDENTICALLY.
 */
export async function computeFingerprint(
	userId: string,
	sessionSecret: string,
	nonce: string,
	ip?: string,
): Promise<string> {
	const input = ip ? `${userId} ${sessionSecret} ${nonce} ${ip}` : `${userId} ${sessionSecret} ${nonce}`;
	const hashBuffer = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(input));
	return Array.from(new Uint8Array(hashBuffer))
		.map((b) => b.toString(16).padStart(2, "0"))
		.join("");
}
